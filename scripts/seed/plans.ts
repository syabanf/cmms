export const jobPlanId = (code: string) => `jp-${code.toLowerCase()}`

export const jobPlans: JobPlan[] = DEFS.map(({ tasks, parts, updated, ...rest }) => ({
  ...rest,
  id: jobPlanId(rest.code),
  tasks: tasks.map((t, i) => ({
    ...(Object.fromEntries(Object.entries(t).filter(([, v]) => v !== null && v !== undefined)) as Task),
    id: `t${i + 1}`,
  })),
  parts: parts.map(([code, qty]) => ({ partId: partId(code), qty })),
  updatedAt: `${updated}T10:00:00+07:00`,
  active: true,
}))

export const JP = (code: string): JobPlan => {
  const plan = jobPlans.find((p) => p.code === code)
  if (!plan) throw new Error(`Unknown job plan ${code}`)
  return plan
}

