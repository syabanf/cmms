type Task = Omit<ChecklistItem, 'id'>
const check = (label: string, required = true): Task => ({ label, type: 'check', required })
const passfail = (label: string, required = true, help?: string): Task => ({ label, type: 'passfail', required, help })
const choice = (label: string, options: string[], required = true): Task => ({ label, type: 'choice', required, options })
const photo = (label: string, required = false): Task => ({ label, type: 'photo', required })
const signature = (label = 'Technician sign-off'): Task => ({ label, type: 'signature', required: true })
const text = (label: string, required = true): Task => ({ label, type: 'text', required })
const num = (label: string, unit: string, required = true): Task => ({ label, type: 'number', unit, required })
const meas = (
  label: string,
  unit: string,
  limits: { min?: number; max?: number; warnMin?: number; warnMax?: number },
  required = true,
): Task => ({
  label,
  type: 'measurement',
  unit,
  required,
  min: limits.min ?? null,
  max: limits.max ?? null,
  warnMin: limits.warnMin ?? null,
  warnMax: limits.warnMax ?? null,
})

const safety = (loto: boolean, hazards: string[], ppe: string[], notes = ''): SafetyRequirement => ({
  loto,
  ...safetyDetail(loto, hazards.map(sf)),
  hazardIds: hazards.map(sf),
  ppeIds: ppe.map(sf),
  notes,
})

